// The Hermes release Link installs, and its commit. Changing it means
// updating [`COMMIT`] (`git rev-parse v<version>^{commit}` in Hermes's
// repository, a release's `v0.x.y` tag, never a `+canary` one) and
// [`INSTALLER`] to `scripts/install.sh` there, with its SHA-256
// (`git show <commit>:scripts/install.sh | sha256sum`), and checking
// [`CONFIG_VERSION`] again.
include!(concat!(env!("OUT_DIR"), "/external-pins.rs"));
const VERSION: &str = HERMES_VERSION;
const COMMIT: &str = HERMES_COMMIT;

/// Hermes's installer (what `hermes-agent.nousresearch.com/install.sh`
/// serves), at [`COMMIT`].
const INSTALLER: harness::Installer = harness::Installer {
    name: "Hermes",
    url: HERMES_URL,
    sha256: HERMES_SHA256,
    companions: &[],
};

/// The API server's port: Hermes's default, unless Link gives the agent
/// another base port (`LNK_PORT`).
fn port() -> u16 {
    harness::base_port(8642)
}

fn main() -> std::process::ExitCode {
    // Safe to hold a secret before anything else: no core dump, no other
    // process of this user reading it.
    link_secretive::process::guard();
    link_core::describe_component!();
    link_settings::output::run(try_main)
}

/// `value` as one line of JSON on stdout: what `lnk-agent` reads.
fn answer(out: &mut Out, value: &(impl serde::Serialize + ?Sized)) -> Result<Done, Report> {
    let line = serde_json::to_string(value).within("writing its answer")?;
    out.data(format!("{line}\n").as_bytes());
    Ok(Done::shown())
}

fn try_main(out: &mut Out) -> Result<Done, Report> {
    link_files::layout::check_exec_environment().within("checking the program directory")?;
    dispatch(out, link_hermes::cli::parse())
}

fn dispatch(out: &mut Out, command: Given) -> Result<Done, Report> {
    match command {
        Given::Uninstall(given) => {
            let args = &given;
            uninstall(args)
        }

        // It reaches a hosted model at the proxy's address
        // (`Model.base_url`), so the proxy can hold the key.
        Given::HermesContract(_) => {
            let mut contract = harness::Contract::new(true);
            contract.features = Some(features::honors());
            // What its hub's agent state gives and takes, which `lnk agent
            // harness set` carries; its own memory files (MEMORY.md and USER.md)
            // among them, exported into Link's folder at a switch away.
            contract.state = state::kinds();
            contract.offline_state = true;
            contract.session_content = state::content();
            contract.native_memory = true;
            // Who the agent is, written into SOUL.md and read back out.
            contract.identity = true;
            // It takes the spec's [instructions] it carries (persona, owner,
            // standing instructions, skills); its features say which.
            contract.instructions = true;
            // Link's bridge carries every connection to its ACP, through
            // the hub, each chat a session of its own: the hub proves its
            // key, reads which agent a message is for and writes its
            // sender into its text.
            contract.proof = true;
            (contract.agent, contract.from) = (true, true);
            answer(out, &contract)
        }
        Given::HermesInstall(_) => install(out),
        Given::HermesConfigure(_) => {
            let mut input = String::new();
            std::io::stdin()
                .read_to_string(&mut input)
                .within("reading settings on stdin")?;
            let settings: Settings =
                serde_json::from_str(&input).within("reading the settings on stdin")?;
            harness::continuation::Context::configure(
                &link_files::home_dir(),
                "hermes",
                &settings,
            )?;
            identity::configure(&link_files::home_dir(), &settings)?;
            if let Some(notes) = &settings.remembered {
                let from = identity::remember(&link_files::home_dir(), notes)?;
                if !from.is_empty() {
                    out.block(Note(sentence!(
                        "Memory from {} is ready for bounded context on the next turn.",
                        link_format::Value::List(from.into_iter().map(Into::into).collect())
                    )));
                }
            }
            // Nothing changed since the last one: Hermes is as it left it.
            let configured = configured();
            let read = configuring::read_by_configure(&input)?;
            let unchanged = configured.unchanged(&read);
            configuring::configure_environment(&settings)?;
            if unchanged {
                configuring::configure_endpoints(&settings)?;
                // The env files may now hold rotated values. Record them
                // without paying for Hermes's structural CLI again.
                configured
                    .done(&read)
                    .within("recording the settings it configured")?;
                return Ok(Done::shown());
            }
            configured.forget();
            configure(&settings)?;
            configuring::configure_endpoints(&settings)?;
            configured
                .done(&read)
                .within("recording the settings it configured")?;
            Ok(Done::shown())
        }
        Given::HermesCommand(_) => answer(out, &launch()?),
        Given::HermesHealth(_) => Ok(if harness::http_ok(port(), "/health") {
            Done::shown()
        } else {
            Done::passed(1)
        }),
        // For `lnk module add`, which checks it is the release it asked for.
        Given::HermesWritten(given) => {
            let home = PathBuf::from(given.home);
            answer(out, &written(&home))
        }
        Given::HermesTraces(_) => answer(out, TRACES),
        // `state schedules`: its own scheduled jobs, and their revision.
        Given::StateSchedules(given) => {
            let schedules = schedules::export_root(&PathBuf::from(given.root))?;
            answer(out, &schedules)
        }
        Given::StateClearSchedules(given) => {
            let root = PathBuf::from(given.root);
            schedules::clear_root(&root, &given.revision, given.context.as_deref())?;
            Ok(Done::shown())
        }
        // `state export`: who the agent is and what it remembers, in
        // ASP's portable forms, for a switch away from it.
        Given::StateExport(_) => {
            let home = link_files::home_dir();
            let state = link_harness_hub::Store::export(
                &state::Hermes {
                    home: home.clone(),
                    programs: installing::programs_root(),
                    cwd: String::new(),
                },
                &link_harness_contract::asp::Kind::ALL,
            )?;
            let state = link_harness_hub::export_personal(
                &home,
                "hermes",
                hermes_home().join("link-threads.json"),
                state,
            )?;
            answer(out, &state)
        }
        Given::StateShow(_) => answer(out, &state()),
        Given::HermesServe(_) => {
            // The hub's logs and the guest's own lines are on this terminal.
            out.hand_over();
            serve()
        }
        Given::HermesEndpoint(_) => {
            let url = format!(
                "http://127.0.0.1:{}{}",
                port(),
                link_connection_contract::acp::ACP_PATH
            );
            answer(out, &url)
        }
        // It speaks no connection itself: Link's bridge carries them.
        Given::HermesConnections(_) => {
            out.data(b"[]\n");
            Ok(Done::shown())
        }
        Given::HermesInternetHosts(_) => answer(out, HOSTS),
        // Only any program: it runs the Python it installed in its home.
        // Its Slack works through Link's proxy, and its installer's git
        // is `developer-tools`, a default.
        Given::HermesNeeds(_) => {
            let needs = harness::Needs {
                needs: vec![harness::Need::runs(
                    &installing::programs_root(),
                    "it runs the Python it installed in its home, and the commands its tools run",
                )],
                // Its installer fetches uv, then runs it.
                install_runs_downloads: true,
                ..Default::default()
            };
            answer(out, &needs)
        }
        // Nothing it links itself: Signal's account is `lnk-signal`'s.
        Given::HermesLink(request) => Err(harness::unsupported_link(&request.connection)),
    }
}

/// Its localhost ports: its endpoint's.
fn ports() -> Vec<u16> {
    vec![port()]
}

/// Of its ports, those served outside its sandbox: its endpoint, where
/// Link's bridge reaches it.
fn served() -> Vec<u16> {
    vec![port()]
}

/// What of `~/.hermes` is the agent (its config, memories, sessions,
/// skills, scheduled jobs): all of it but its code (`hermes-agent`), the
/// Python, Node and other tools its package manager keeps (`tools`) and
/// the package environments it makes from them (`installs`), logs and
/// caches, and `.env`, which `configure` writes from Link's settings.
fn state() -> harness::State {
    let path = |p: &str| format!("~/.hermes{p}");
    harness::State {
        // signal-cli's account is lnk-signal's to say: `lnk agent move`
        // adds it.
        include: vec![path(""), "~/.lnk/data/agents/context".into()],
        exclude: [
            "/hermes-agent",
            "/tools",
            "/installs",
            "/bin",
            "/logs",
            "/cache",
            "/.env",
        ]
        .into_iter()
        .map(path)
        .collect(),
    }
}

/// The hosts `install` and `configure` reach, behind their proxy
/// (`lnk-hermes hosts`): the installer and Hermes's code, uv and Python,
/// the tools and packages its package manager installs (its
/// `pm/lock.json`), and what it fetches from GitHub.
const HOSTS: &[&str] = &[
    // Its installer and its code; uv, Python and its tools' releases.
    "github.com",
    "*.githubusercontent.com",
    // The Python uv downloads to start its installer where there's none.
    "astral.sh",
    "*.astral.sh",
    // Hermes's packages, and those of its channels and tools.
    "pypi.org",
    "files.pythonhosted.org",
    "registry.npmjs.org",
    // Node, which builds its terminal and web apps.
    "nodejs.org",
    "unofficial-builds.nodejs.org",
];

/// The newest settings Hermes [`VERSION`] reads: its
/// `DEFAULT_CONFIG["_config_version"]` (`hermes_cli/config_defaults.py`),
/// checked again whenever [`VERSION`] changes.
const CONFIG_VERSION: &str = "52";

/// The settings version that wrote the install whose home is `home`
/// (`_config_version` in its `config.yaml`), refused when it's newer than
/// [`CONFIG_VERSION`]: Link would run them on an older Hermes.
fn written(home: &std::path::Path) -> traces::Written {
    let text = std::fs::read_to_string(home.join("config.yaml")).unwrap_or_default();
    let config: serde_norway::Value = serde_norway::from_str(&text).unwrap_or_default();
    let version = match config.get("_config_version") {
        Some(serde_norway::Value::Number(n)) => Some(n.to_string()),
        Some(serde_norway::Value::String(s)) => Some(s.clone()),
        _ => None,
    };
    let refused = version
        .as_deref()
        .filter(|v| traces::newer(v, CONFIG_VERSION))
        .map(|v| {
            format!(
                "its settings are version {v}, newer than the {CONFIG_VERSION} of the Hermes \
                 {VERSION} Link runs, which can't read them: update Link first"
            )
        });
    traces::Written { version, refused }
}

/// Where Hermes writes when it isn't boxed: its folder, with its settings,
/// secrets and its own login, its launcher, its own gateway service. Not
/// the Python uv installed to start its installer (`~/.local/share/uv`):
/// other programs share that, and `lnk agent delete` deletes what is
/// listed here.
const TRACES: &[Trace] = &[
    Trace::new(Kind::Home, "~/.hermes"),
    Trace::new(Kind::Config, "~/.hermes/config.yaml"),
    Trace::new(Kind::Secrets, "~/.hermes/.env"),
    Trace::new(Kind::Login, "~/.hermes/auth.json"),
    Trace::new(Kind::Profile, "~/.hermes/profiles/{agent}"),
    Trace::new(Kind::Program, "~/.local/bin/hermes"),
    Trace::new(
        Kind::Service,
        "~/Library/LaunchAgents/ai.hermes.gateway.plist",
    ),
    Trace::new(
        Kind::Service,
        "~/.config/systemd/user/hermes-gateway.service",
    ),
];

fn launch() -> Result<Launch, Report> {
    let bin = bin().ok_or_else(not_installed)?;
    let dir = bin
        .parent()
        .map(|d| d.display().to_string())
        .unwrap_or_default();
    Ok(Launch {
        argv: vec![installed().display().to_string(), "serve".into()],
        env: [
            (
                "HERMES_HOME".to_string(),
                hermes_home().display().to_string(),
            ),
            (
                "PATH".into(),
                format!("{dir}:/usr/bin:/bin:/usr/sbin:/sbin"),
            ),
            // Its Node through HTTPS_PROXY, Link's proxy, like everything
            // else it runs.
            ("NODE_USE_ENV_PROXY".into(), "1".into()),
        ]
        .into(),
        // HOME is its home folder: ~/.hermes, its launcher and its Python are all
        // in there.
        write: vec![],
        read: vec![],
        ports: ports(),
        serve: Some(served()),
        services: vec!["ai.hermes.gateway".into(), "hermes-gateway.service".into()],
        // The 180 s every harness had before an adapter could say.
        wait_secs: Some(180),
    })
}

/// Where `install` puts this program, in its home: the sandbox runs
/// programs only from there.
fn installed() -> PathBuf {
    installing::programs_root().join("bin/lnk-hermes")
}

/// The endpoint: the hub on its port until stopped, `hermes-acp` behind
/// it in the agent's files.
fn serve() -> Result<Done, Report> {
    let files = std::env::var("LNK_FILES").map_err(|_| {
        Report::error(sentence!("The variable LNK_FILES isn't set."))
            .why(sentence!("The program lnk agent start runs this command."))
            .next(cmd!("lnk agent start"), "start the agent")
            .exit(Exit::Usage)
    })?;
    let key = harness::read_env_file(&configuring::link_env(), configuring::ENDPOINT_KEY)
        .filter(|k| !k.is_empty());
    let payload = workarounds::payload(&installing::programs_root())?;
    let gateway = std::sync::Arc::new(gateway::Gateway::new(
        {
            let files = files.clone();
            move || {
                let mut run = hermes()?;
                run.current_dir(&files);
                Ok(run)
            }
        },
        hermes_home(),
        launch()?.wait(),
    ));
    let acp = link_harness_hub::spawning({
        let files = files.clone();
        move || {
            let mut acp = payload.acp(&hermes_home());
            let (name, value) = gateway::managed();
            acp.env(name, value).current_dir(&files);
            acp
        }
    });
    let start: link_harness_hub::Start = Box::new({
        let gateway = gateway.clone();
        move || {
            gateway.ensure()?;
            acp()
        }
    });
    let served = link_harness_hub::Hub::new(link_harness_hub::Config {
        start,
        cwd: files.clone(),
        key: key.map(link_secretive::Secret::from),
        agent: std::env::var("LNK_AGENT").ok().filter(|a| !a.is_empty()),
        sessions: hermes_home().join("link-threads.json"),
        state: Some(std::sync::Arc::new(state::Hermes {
            home: link_files::home_dir(),
            programs: installing::programs_root(),
            cwd: files,
        })),
        // Not yet shown to take MCP servers over ACP: Link's tools are in
        // its `config.yaml`.
        tools: link_harness_hub::Tools::default(),
    })
    .with_continuity(&link_files::home_dir())?
    .serve(port());
    let stopped = gateway.stop();
    served?;
    stopped.within("stopping Hermes's owned gateway")?;
    Ok(Done::shown())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_unadvertised_native_connection_is_refused_by_the_real_handler() {
        use clap::FromArgMatches;
        let parser = link_hermes::cli::command();
        let matches = parser
            .clone()
            .try_get_matches_from(["lnk-hermes", "connections"])
            .unwrap();
        let parsed = link_hermes::cli::Cli::from_arg_matches(&matches).unwrap();
        let (mut out, captured) = Out::capture(false, &["lnk-hermes", "connections"]);
        assert!(dispatch(&mut out, parsed.command).is_ok());
        assert_eq!(captured.stdout(), "[]\n");
        for again in [false, true] {
            let mut argv = vec!["lnk-hermes", "link", "signal"];
            if again {
                argv.push("--again");
            }
            let matches = parser.clone().try_get_matches_from(&argv).unwrap();
            let parsed = link_hermes::cli::Cli::from_arg_matches(&matches).unwrap();
            let (mut out, captured) = Out::capture(false, &argv);
            let report =
                dispatch(&mut out, parsed.command).expect_err("unsupported native link succeeded");
            assert_eq!(report.exit, Exit::Usage);
            assert!(captured.stdout().is_empty());
        }
    }

    #[test]
    fn only_its_api_is_served() {
        assert_eq!(ports(), [port()]);
        assert_eq!(served(), [port()]);
    }
}

