//! `lnk-hermes`: the Hermes Agent adapter. `lnk-agent` runs it; see
//! `link_harness_contract::harness` for the commands.
//!
//! Hermes is installed with its own installer, at a pinned release
//! ([`VERSION`]), without questions, into the read-only
//! `~/.lnk/exec/harnesses/hermes` (its own Python and Node included, in its
//! `tools`), sealed there with the adapter's workarounds; its runtime data
//! is in `~/.hermes`. It's configured with `hermes config set`, and run as `hermes-acp`, its ACP over stdio, behind the
//! hub (`link_harness_hub`): this program's `serve` is its endpoint, ACP
//! at its port's `/acp`, each of Link's threads a Hermes session. Keys go
//! in `~/.hermes/.env`, never on a command line; the hub's, generated by
//! Link, in `~/.hermes/link.env`.

